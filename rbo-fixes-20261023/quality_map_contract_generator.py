"""Generate anonymous Q25 adapters calling the actual production IR methods.

Derived from the initial Filter-placement adapter by harness_provenance, with
per-definition observations, partial/no fusion, copies, expression replacement
and preserved-side Join controls. Never persist rendered C++ or diagnostics.
These local contracts do not establish native row semantics or evaluation counts.
"""
import hashlib
import json


def cases():
    return [*(f'q25_fusion_{bottom}_{top}_{movement}_{operation}'
              for bottom, top in ((0, 0), (0, 1), (1, 0), (1, 1))
              for movement in ('all', 'partial', 'none')
              for operation in ('direct', 'copy', 'replace')),
            *(f'q25_boundary_{boundary}_{operation}'
              for boundary in ('Filter', 'Inner', 'Left', 'Full')
              for operation in ('direct', 'copy', 'replace'))]


def _line(statement):
    return statement + ';\n'


def _check(expression):
    return _line('Check(' + expression + ')')


def _prelude():
    includes = ('ydb/core/kqp/ut/rbo/kqp_rbo_test_helpers.h', 'iostream', 'stdexcept')
    result = ''.join('#include <' + path + '>\n' for path in includes)
    result += 'using namespace NKikimr::NKqp;\nusing namespace NYql;\n'
    result += 'static unsigned Checks = 0;\nstatic void Check(bool value) { ++Checks; if (!value) throw std::runtime_error("contract"); }\n'
    # Baseline and fixed builds use the same generated bytes. The adapter only
    # observes the public representation available in that build; it never
    # substitutes an optimizer operation or writes private production state.
    result += 'template<class T> bool Marked(T& map, TInfoUnitId id) {\n'
    result += 'Check(map.FindOutputElement(id) != nullptr);\n'
    result += 'if constexpr (requires { map.FindOutputElement(id)->NeedsPushdown(); }) return map.FindOutputElement(id)->NeedsPushdown();\n'
    result += 'else return map.NeedToPush;\n}\n'
    result += 'static TOpMap& Owner(IOperator& root, TInfoUnitId id) {\n'
    result += 'TOpMap* found = nullptr;\n'
    result += 'for (const auto& item : IterateSubtree(&root)) { if (item.Current->Kind != EOperator::Map) continue; auto& map = CastOperator<TOpMap>(*item.Current); if (map.FindOutputElement(id)) { Check(found == nullptr); found = &map; } }\n'
    result += 'Check(found != nullptr); return *found;\n}\n'
    result += 'static void Definition(IOperator& root, TInfoUnitId id, bool marked) { auto& map = Owner(root, id); Check(Marked(map, id) == marked); }\n'
    result += 'static bool Defines(IOperator& root, TInfoUnitId id) {\n'
    result += 'for (const auto& item : IterateSubtree(&root)) { if (item.Current->Kind == EOperator::Map && CastOperator<TOpMap>(*item.Current).FindOutputElement(id)) return true; } return false;\n}\n'
    return result


def _transform(operation, root, ids):
    body = ''
    if operation == 'copy':
        body += _line('TSubstitutions renames')
        body += _line(root + ' = ' + root + '->Copy(f.Props, renames)')
        body += _check(root + '.Get() != nullptr')
        for name in ids:
            body += _check('renames.Find(' + name + ') != nullptr')
            body += _line(name + ' = renames.At(' + name + ')')
    elif operation == 'replace':
        for name in ids:
            # Exercise the production rebinding setter with a fresh expression
            # wrapper, retaining demand and dependency identity.
            body += '{ auto& owner = Owner(*' + root + ', ' + name + ');\n'
            body += 'auto expression = owner.FindOutputElement(' + name + ')->GetExpression().ApplyRenames(TSubstitutions{});\n'
            body += _line('owner.SetMapElementExpression(' + name + ', std::move(expression))')
            body += '}\n'
    return body


def _fusion(case):
    _, _, bottom_flag, top_flag, movement, operation = case.split('_')
    statements = ['const auto source = f.Id()', 'auto lower = f.Id(), independent = f.Id(), dependent = f.Id()',
                  'auto barrier = MakeIntrusive<TOpFilter>(f.Read({source}), f.Pos, MakeConstant("Bool", "true", f.Pos, &f.ExprCtx))',
                  'TMapIUs bottomDefinitions, topDefinitions',
                  'bottomDefinitions.Add(lower, MakeUnaryCallable("Just", f.Column(source)))']
    if movement in ('all', 'partial'):
        statements += ['topDefinitions.Add(independent, MakeUnaryCallable("Just", f.Column(source)))']
    if movement in ('partial', 'none'):
        statements += ['topDefinitions.Add(dependent, MakeUnaryCallable("Just", f.Column(lower)))']
    statements += [
        'auto bottom = MakeIntrusive<TOpMap>(barrier, f.Pos, std::move(bottomDefinitions), ' + ('true' if bottom_flag == '1' else 'false') + ')',
        'auto top = MakeIntrusive<TOpMap>(bottom, f.Pos, std::move(topDefinitions), ' + ('true' if top_flag == '1' else 'false') + ')',
        'TPushMapElementsIntoMapRule fusion',
        'auto result = fusion.SimpleMatchAndApply(top, f.RboCtx, f.Props)']
    body = ''.join(map(_line, statements))
    ids = ['lower'] + (['independent'] if movement in ('all', 'partial') else []) + (['dependent'] if movement in ('partial', 'none') else [])
    if movement == 'all':
        body += _check('result.Get() == bottom.Get()')
    elif movement == 'partial':
        body += _check('result.Get() != top.Get() && result->Kind == EOperator::Map')
        body += _check('CastOperator<TOpMap>(*result).GetMapElements().Keys() == TUnorderedIUs({dependent})')
    else:
        body += _check('result.Get() == top.Get()')
    body += _transform(operation, 'result', ids)
    for name in ids:
        flag = bottom_flag if name == 'lower' else top_flag
        body += _line('Definition(*result, ' + name + ', ' + ('true' if flag == '1' else 'false') + ')')
    if movement in ('all', 'partial'):
        body += _check('&Owner(*result, lower) == &Owner(*result, independent)')
    if movement in ('partial', 'none'):
        body += _check('&Owner(*result, lower) != &Owner(*result, dependent)')
    # Push the actual lower map through its Filter, then inspect each original
    # definition's location independently of the stored flag representation.
    body += _line('TIntrusivePtr<IOperator> candidate = ' + ('result' if movement == 'all' else 'result->GetChild(0)'))
    body += _line('TPushMapElementsThroughInputRule push')
    body += _line('auto pushed = push.SimpleMatchAndApply(candidate, f.RboCtx, f.Props)')
    body += 'bool crossed = false; unsigned barriers = 0, lowerSeen = 0, independentSeen = 0;\n'
    body += 'for (auto* node = pushed.Get(); node; node = node->GetChildCount() ? node->GetChild(0).Get() : nullptr) {\n'
    body += 'if (node->Kind == EOperator::Filter) { crossed = true; ++barriers; }\n'
    body += 'if (node->Kind != EOperator::Map) continue; auto& map = CastOperator<TOpMap>(*node);\n'
    body += 'if (map.FindOutputElement(lower)) { ++lowerSeen; Check(crossed == ' + ('true' if bottom_flag == '1' else 'false') + '); }\n'
    if movement in ('all', 'partial'):
        body += 'if (map.FindOutputElement(independent)) { ++independentSeen; Check(crossed == ' + ('true' if top_flag == '1' else 'false') + '); }\n'
    body += '}\n'
    body += _check('barriers == 1 && lowerSeen == 1 && independentSeen == ' + ('1' if movement in ('all', 'partial') else '0'))
    if movement == 'all':
        body += _line('result = pushed')
    else:
        body += _line('result->SetChild(0, pushed)')
        body += _line('result->Props.OutputIUs.reset()')
    for name in ids:
        flag = bottom_flag if name == 'lower' else top_flag
        body += _line('Definition(*result, ' + name + ', ' + ('true' if flag == '1' else 'false') + ')')
    return body


def _boundary(case):
    _, _, boundary, operation = case.split('_')
    statements = ['const auto left = f.Id(), right = f.Id()', 'auto guarded = f.Id(), leftDefinition = f.Id(), rightDefinition = f.Id()',
                  'TIntrusivePtr<IOperator> boundary']
    if boundary == 'Filter':
        statements += ['boundary = MakeIntrusive<TOpFilter>(f.Read({left}), f.Pos, MakeBinaryPredicate("==", f.Column(left), MakeConstant("Int32", "1", f.Pos, &f.ExprCtx)))']
    else:
        statements += ['boundary = MakeIntrusive<TOpJoin>(f.Read({left}), f.Read({right}), f.Pos, ' + json.dumps(boundary) + ', TPairedIUs{{left, right}})']
    statements += ['TMapIUs bottomDefinitions, topDefinitions',
                   'bottomDefinitions.Add(guarded, MakeEnsure(f.Column(left), MakeBinaryPredicate("==", f.Column(left), MakeConstant("Int32", "1", f.Pos, &f.ExprCtx)), "guard"))',
                   'topDefinitions.Add(leftDefinition, MakeUnaryCallable("Just", f.Column(left)))']
    if boundary != 'Filter':
        statements += ['topDefinitions.Add(rightDefinition, MakeUnaryCallable("Just", f.Column(right)))']
    statements += ['auto bottom = MakeIntrusive<TOpMap>(boundary, f.Pos, std::move(bottomDefinitions), false)',
                   'auto top = MakeIntrusive<TOpMap>(bottom, f.Pos, std::move(topDefinitions), true)',
                   'TPushMapElementsIntoMapRule fusion',
                   'auto fused = fusion.SimpleMatchAndApply(top, f.RboCtx, f.Props)']
    body = ''.join(map(_line, statements))
    ids = ['guarded', 'leftDefinition'] + (['rightDefinition'] if boundary != 'Filter' else [])
    body += _transform(operation, 'fused', ids)
    for name in ids:
        body += _line('Definition(*fused, ' + name + ', ' + ('false' if name == 'guarded' else 'true') + ')')
    body += _line('TPushMapElementsThroughInputRule push')
    body += _line('auto result = push.SimpleMatchAndApply(fused, f.RboCtx, f.Props)')
    body += _check('result->Kind == EOperator::Map')
    body += _line('auto& kept = CastOperator<TOpMap>(*result)')
    body += _check('kept.FindOutputElement(guarded) != nullptr')
    body += _check('kept.FindOutputElement(guarded)->GetExpression().GetExpressionBody()->IsCallable("Ensure")')
    body += _line('auto rewritten = kept.GetInput()')
    body += _check('rewritten->Kind == EOperator::' + ('Filter' if boundary == 'Filter' else 'Join'))
    if boundary == 'Filter':
        body += _check('Defines(*rewritten->GetChild(0), leftDefinition)')
        body += _check('!Defines(*rewritten->GetChild(0), guarded)')
    else:
        left_moved = boundary in ('Inner', 'Left')
        right_moved = boundary == 'Inner'
        body += _check('Defines(*rewritten->GetChild(0), leftDefinition) == ' + str(left_moved).lower())
        body += _check('Defines(*rewritten->GetChild(1), rightDefinition) == ' + str(right_moved).lower())
        body += _check('(kept.FindOutputElement(leftDefinition) != nullptr) == ' + str(not left_moved).lower())
        body += _check('(kept.FindOutputElement(rightDefinition) != nullptr) == ' + str(not right_moved).lower())
        body += _check('!Defines(*rewritten->GetChild(0), guarded) && !Defines(*rewritten->GetChild(1), guarded)')
    for name in ids:
        body += _line('Definition(*result, ' + name + ', ' + ('false' if name == 'guarded' else 'true') + ')')
    return body


def _body(case):
    if case not in cases():
        raise ValueError('Unknown Map contract case')
    return 'NKikimr::NKqp::NTests::TIdTestContext f;\n' + (_fusion(case) if '_fusion_' in case else _boundary(case))


def render_cpp(case):
    text = _prelude() + 'int main() { try {\n' + _body(case)
    text += 'std::cout << ' + json.dumps('{"checks_passed":') + ' << Checks << ' + json.dumps(',"status":"passed"}\n') + '; return 0;\n'
    text += '} catch (...) { std::cout << ' + json.dumps('{"status":"failed"}\n') + '; return 1; } }\n'
    return text


def render_cpp_suite(selected=None):
    selected = cases() if selected is None else list(selected)
    if not selected or len(set(selected)) != len(selected) or any(case not in cases() for case in selected):
        raise ValueError('Expected distinct known Map contract cases')
    text = _prelude()
    for index, case in enumerate(selected):
        text += 'static void Run' + str(index) + '() {\n' + _body(case) + '}\n'
    text += 'int main() { unsigned failures = 0;\n'
    for index, case in enumerate(selected):
        text += 'Checks = 0; bool passed' + str(index) + ' = true;\n'
        text += 'try { Run' + str(index) + '(); } catch (...) { passed' + str(index) + ' = false; ++failures; }\n'
        text += 'std::cout << ' + json.dumps('{"case_index":' + str(index) + ',"checks":') + ' << Checks << '
        text += json.dumps(',"passed":') + ' << (passed' + str(index) + ' ? "true" : "false") << ' + json.dumps('}\n') + ';\n'
    return text + 'return failures ? 1 : 0; }\n'


